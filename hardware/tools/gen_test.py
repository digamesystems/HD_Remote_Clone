"""Generates hardware/hd_remote/test.kicad_sch (first draft): rail and signal test
points, GND loops, a debug strobe, and a DNP UART header. Test points on nets
local to another sheet (IR_E1/2, IR_BASE, PROG) and the battery current link
live on those sheets. Run once; after editing the sheet in KiCad, don't rerun.

    python -I hardware/tools/gen_test.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schgen  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ_DIR = os.path.join(HERE, "..", "hd_remote")
ROOT = os.path.join(PROJ_DIR, "hd_remote.kicad_sch")
OUT = os.path.join(PROJ_DIR, "test.kicad_sch")
PROJECT = "hd_remote"
SHEET_UUID = "80ad4f75-b19e-4c6d-a5fc-4b7c9dbecf60"

PAD = "TestPoint:TestPoint_Pad_D1.5mm"
LOOP = "TestPoint:TestPoint_Keystone_5000-5004_Miniature"
GLOBAL = ("IR_TX", "VBAT_SENSE", "NRF_IRQ_OPT", "U0TXD", "U0RXD", "EN", "IO0")


def build():
    s = schgen.Sheet(PROJECT, "test.kicad_sch", "Test and debug", schgen.root_uuid(ROOT), SHEET_UUID,
                     ref_base=600)
    s.text("Test points: SMD pads on the back unless noted. Others on their own sheets:\n"
           "IR_E1, IR_E2, IR_BASE (IR), PROG and the battery current link JP101 (Power and USB).", 8, 6)

    s.text("Rails", 8, 16)
    for i, net in enumerate(("VBAT", "+3V3", "VBUS")):
        s.part("Connector:TestPoint", "TP", net, 10 + 8 * i, 22, {"1": net}, {"Footprint": PAD}, GLOBAL)

    s.text("GND loops for scope ground clips\n(one near the IR stage, one near the radio)", 40, 16)
    for i in range(3):
        s.part("Connector:TestPoint", "TP", "GND", 42 + 8 * i, 22, {"1": "GND"}, {"Footprint": LOOP}, GLOBAL)

    s.text("Signals", 8, 36)
    for i, (net, value) in enumerate((("IR_TX", "IR_TX"), ("VBAT_SENSE", "VBAT_SENSE"))):
        s.part("Connector:TestPoint", "TP", value, 10 + 12 * i, 42, {"1": net}, {"Footprint": PAD}, GLOBAL)

    s.text("Debug strobe on GPIO 13: firmware toggles it at RF / IR step\n"
           "boundaries for logic-analyzer timing. Shared with the optional\n"
           "nRF24 IRQ link (R401, DNP): don't fit both.", 40, 36)
    s.part("Connector:TestPoint", "TP", "DBG_GPIO13", 42, 46, {"1": "NRF_IRQ_OPT"}, {"Footprint": PAD}, GLOBAL)

    s.text("UART header (DNP): flash/monitor with an external 3.3 V USB-serial\n"
           "adapter if the onboard CP2102N misbehaves. Unplug USB-C first.\n"
           "Adapter TX -> U0RXD, adapter RX <- U0TXD. 3V3 pin: power in OR out,\n"
           "not both. EN/IO0 for manual or DTR/RTS-driven reset.", 8, 56)
    s.part("Connector_Generic:Conn_01x06", "J", "UART", 14, 74, {
        "1": "GND", "2": "+3V3", "3": "U0TXD", "4": "U0RXD", "5": "EN", "6": "IO0",
    }, {"Footprint": "Connector_PinHeader_2.54mm:PinHeader_1x06_P2.54mm_Vertical"}, GLOBAL, dnp=True)

    text = s.render({
        "title": "HD Platinum remote replacement: Test and debug",
        "date": "2026-11-12",
        "rev": "0.1",
        "comments": ["Draft, generated by hardware/tools/gen_test.py", "Spec: docs/HARDWARE.md"],
    })
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    added = schgen.add_sheet_to_root(ROOT, PROJECT, SHEET_UUID, "Test and debug", "test.kicad_sch",
                                     7, 130, 30)
    print("wrote", OUT, "| root sheet block", "added" if added else "already present")


if __name__ == "__main__":
    build()

"""Generates hardware/hd_remote/nrf24.kicad_sch (first draft) from docs/HARDWARE.md:
the 2x4 socket for the nRF24 module, its decoupling, and an optional IRQ link.
Run once; after editing the sheet in KiCad, don't rerun.

    python -I hardware/tools/gen_nrf24.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schgen  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ_DIR = os.path.join(HERE, "..", "hd_remote")
ROOT = os.path.join(PROJ_DIR, "hd_remote.kicad_sch")
OUT = os.path.join(PROJ_DIR, "nrf24.kicad_sch")
PROJECT = "hd_remote"
SHEET_UUID = "6e8b2d53-9f7c-4a4b-83da-2f5a7b9cad40"
GLOBAL = ("NRF_CE", "NRF_CSN", "NRF_SCK", "NRF_MOSI", "NRF_MISO", "NRF_IRQ_OPT")


def build():
    s = schgen.Sheet(PROJECT, "nrf24.kicad_sch", "nRF24", schgen.root_uuid(ROOT), SHEET_UUID, ref_base=400)

    s.text("nRF24L01+ module (the screened hiBCTR modules) in a 2x4 socket, 2.54 mm.\n"
           "Pin numbers as on the module (docs/WIRING.md): odd row 1 GND, 3 CE, 5 SCK, 7 MISO;\n"
           "even row 2 VCC, 4 CSN, 6 MOSI, 8 IRQ. 3.3 V only.\n"
           "Layout: the module's PCB antenna overhangs the board edge; no copper under it, all\n"
           "layers. Check the socket's orientation against the module (pin 1 = square pad = GND).",
           8, 8)
    s.part("Connector_Generic:Conn_02x04_Odd_Even", "J", "nRF24_socket", 24, 36, {
        "1": "GND", "2": "NRF_VCC", "3": "NRF_CE", "4": "NRF_CSN",
        "5": "NRF_SCK", "6": "NRF_MOSI", "7": "NRF_MISO", "8": "NRF_IRQ",
    }, {"Footprint": "Connector_PinSocket_2.54mm:PinSocket_2x04_P2.54mm_Vertical"}, GLOBAL)

    s.text("Supply filter: 0 ohm fitted by default. If range or packet loss points to supply\n"
           "noise, fit a ferrite bead instead (e.g. 600 ohm at 100 MHz, low DCR, 0603), and\n"
           "check for bead/ceramic resonance. Caps at the socket's VCC/GND pins: 100 nF closest.\n"
           "Bulk (DNP): fit 47-100 uF only for a PA/LNA module (>100 mA in TX).", 40, 18)
    s.part("Device:FerriteBead_Small", "FB", "0R (or bead)", 44, 34, {"1": "+3V3", "2": "NRF_VCC"},
           {"Footprint": "Inductor_SMD:L_0603_1608Metric",
            "Description": "0 ohm link by default; ferrite bead option for the nRF24 supply"}, GLOBAL)
    s.part("Device:C_Small", "C", "10u", 50, 34, {"1": "NRF_VCC", "2": "GND"},
           {"Footprint": "Capacitor_SMD:C_0805_2012Metric"}, GLOBAL)
    s.part("Device:C_Small", "C", "100n", 54, 34, {"1": "NRF_VCC", "2": "GND"},
           {"Footprint": "Capacitor_SMD:C_0603_1608Metric"}, GLOBAL)
    s.part("Device:C_Small", "C", "100u", 58, 34, {"1": "NRF_VCC", "2": "GND"},
           {"Footprint": "Capacitor_SMD:C_1206_3216Metric",
            "Description": "Bulk for a PA/LNA module only"}, GLOBAL, dnp=True)

    s.text("IRQ is unused by the firmware. Optional\nlink to GPIO 13: fit a 0 ohm here (DNP).", 74, 26)
    s.part("Device:R_Small", "R", "0", 78, 36, {"1": "NRF_IRQ", "2": "NRF_IRQ_OPT"},
           {"Footprint": "Resistor_SMD:R_0603_1608Metric"}, GLOBAL, dnp=True)

    text = s.render({
        "title": "HD Platinum remote replacement: nRF24",
        "date": "2026-11-12",
        "rev": "0.1",
        "comments": ["Draft, generated by hardware/tools/gen_nrf24.py", "Spec: docs/HARDWARE.md"],
    })
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    added = schgen.add_sheet_to_root(ROOT, PROJECT, SHEET_UUID, "nRF24", "nrf24.kicad_sch", 5, 70, 30)
    print("wrote", OUT, "| root sheet block", "added" if added else "already present")


if __name__ == "__main__":
    build()

"""Generates hardware/hd_remote/ui.kicad_sch (first draft) from docs/HARDWARE.md:
the 8 keys with pull-downs, the A/B channel switch, and the red/green indicator.
Run once; after editing the sheet in KiCad, don't rerun.

    python -I hardware/tools/gen_ui.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schgen  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ_DIR = os.path.join(HERE, "..", "hd_remote")
ROOT = os.path.join(PROJ_DIR, "hd_remote.kicad_sch")
OUT = os.path.join(PROJ_DIR, "ui.kicad_sch")
PROJECT = "hd_remote"
SHEET_UUID = "7f9c3e64-a08d-4b5c-94eb-3a6b8cadbe50"

R = "Resistor_SMD:R_0603_1608Metric"
C = "Capacitor_SMD:C_0603_1608Metric"
KEY = "Button_Switch_THT:SW_PUSH_6mm_H13mm"      # tall plunger, to reach through the lid
SETUP_KEY = "Button_Switch_THT:SW_PUSH_6mm_H5mm"  # recessed: pressed with a paperclip

# (net, label on the key, GPIO) in the original remote's order
KEYS = [
    ("BTN_UP", "UP", 32), ("BTN_DOWN", "DOWN", 33), ("BTN_ALL", "ALL", 25),
    ("BTN_SETUP", "SETUP", 26), ("BTN_G1", "1", 34), ("BTN_G2", "2", 35),
    ("BTN_G3", "3", 36), ("BTN_G4", "4", 27),
]
GLOBAL = tuple(k[0] for k in KEYS) + ("AB_SW", "LED_RED", "LED_GREEN")


def build():
    s = schgen.Sheet(PROJECT, "ui.kicad_sch", "Buttons and LEDs", schgen.root_uuid(ROOT), SHEET_UUID,
                     ref_base=500)

    s.text("Keys: active-high to 3V3, 100k pull-down each (all on RTC GPIOs, for ext1 deep-sleep\n"
           "wake with ANY_HIGH). GPIO 34/35/36 have no internal pulls, so the external ones are\n"
           "required there. 100 nF debounce caps are optional (DNP); the firmware debounces.\n"
           "Key footprints are placeholders until the enclosure is chosen (6 mm THT, tall plunger;\n"
           "SETUP short, recessed).", 8, 6)
    for i, (net, name, gpio) in enumerate(KEYS):
        gx = 12 + (i % 4) * 22
        gy = 32 + (i // 4) * 24
        s.text("%s (GPIO %d)" % (name, gpio), gx - 3, gy - 7)
        s.part("Switch:SW_Push", "SW", name, gx, gy, {"1": "+3V3", "2": net},
               {"Footprint": SETUP_KEY if name == "SETUP" else KEY}, GLOBAL)
        s.part("Device:R_Small", "R", "100k", gx + 6, gy + 6, {"1": net, "2": "GND"},
               {"Footprint": R}, GLOBAL)
        s.part("Device:C_Small", "C", "100n", gx + 10, gy + 6, {"1": net, "2": "GND"},
               {"Footprint": C}, GLOBAL, dnp=True)

    s.text("A/B IR channel switch (GPIO 21): low = A, high = B.\n"
           "Read on wake; draws nothing in either position.\nWhich throw is \"A\" depends on the part.",
           8, 80)
    s.part("Switch:SW_SPDT", "SW", "A/B", 16, 94, {"2": "AB_SW", "1": "GND", "3": "+3V3"},
           {"Footprint": "Button_Switch_SMD:SW_SPDT_PCM12"}, GLOBAL)

    s.text("Indicator: 3-lead red/green, common cathode, diffused. ~4 mA each, PWM.\n"
           "Pick a ~2 V green (not 3 V InGaN), or lower its resistor.\n"
           "CHECK which outer leg is red on the part bought; the pinout varies.", 44, 80)
    s.part("Device:LED_Dual_AKA", "D", "Red/Green CC", 56, 96,
           {"1": "LED_R_A", "3": "LED_G_A", "2": "GND"},
           {"Footprint": "LED_THT:LED_D5.0mm-3", "Description": "A1 = red, A2 = green (check the part)"},
           GLOBAL)
    s.part("Device:R_Small", "R", "330", 70, 92, {"1": "LED_RED", "2": "LED_R_A"}, {"Footprint": R}, GLOBAL)
    s.part("Device:R_Small", "R", "270", 76, 92, {"1": "LED_GREEN", "2": "LED_G_A"}, {"Footprint": R}, GLOBAL)

    text = s.render({
        "title": "HD Platinum remote replacement: Buttons and LEDs",
        "date": "2026-11-12",
        "rev": "0.1",
        "comments": ["Draft, generated by hardware/tools/gen_ui.py", "Spec: docs/HARDWARE.md"],
    })
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    added = schgen.add_sheet_to_root(ROOT, PROJECT, SHEET_UUID, "Buttons and LEDs", "ui.kicad_sch",
                                     6, 130, 10)
    print("wrote", OUT, "| root sheet block", "added" if added else "already present")


if __name__ == "__main__":
    build()

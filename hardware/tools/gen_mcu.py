"""Generates hardware/hd_remote/mcu.kicad_sch (first draft) from docs/HARDWARE.md:
ESP32-WROOM-32E, decoupling, EN reset, BOOT button, and a global label for every
GPIO in the spec's pin map. Run once; after editing the sheet in KiCad, don't rerun.

    python -I hardware/tools/gen_mcu.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schgen  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ_DIR = os.path.join(HERE, "..", "hd_remote")
ROOT = os.path.join(PROJ_DIR, "hd_remote.kicad_sch")
OUT = os.path.join(PROJ_DIR, "mcu.kicad_sch")
PROJECT = "hd_remote"
SHEET_UUID = "4c3e9b70-1f2a-4b8c-9d64-7a5e2f1c3b20"

R = "Resistor_SMD:R_0603_1608Metric"
C = "Capacitor_SMD:C_0603_1608Metric"
C0805 = "Capacitor_SMD:C_0805_2012Metric"
BUTTON = "Button_Switch_SMD:SW_Push_1P1T_NO_CK_KMR2"

# Pin map (docs/HARDWARE.md). Net names are shared with the other sheets.
GPIO_NETS = {
    "8": "BTN_UP",        # IO32
    "9": "BTN_DOWN",      # IO33
    "6": "BTN_G1",        # IO34, input-only
    "7": "BTN_G2",        # IO35, input-only
    "4": "BTN_G3",        # SENSOR_VP = IO36, input-only
    "12": "BTN_G4",       # IO27
    "10": "BTN_ALL",      # IO25
    "11": "BTN_SETUP",    # IO26
    "33": "AB_SW",        # IO21
    "5": "VBAT_SENSE",    # SENSOR_VN = IO39, ADC1_CH3
    "26": "IR_TX",        # IO4
    "13": "IR_RX",        # IO14, optional receiver footprint
    "36": "LED_RED",      # IO22
    "27": "LED_GREEN",    # IO16
    "30": "NRF_SCK",      # IO18
    "31": "NRF_MISO",     # IO19
    "37": "NRF_MOSI",     # IO23
    "29": "NRF_CSN",      # IO5 (strapping; CSN idles high)
    "28": "NRF_CE",       # IO17
    "16": "NRF_IRQ_OPT",  # IO13: spare, optional nRF24 IRQ link
    "3": "EN",
    "25": "IO0",
    "35": "U0TXD",        # TXD0 = IO1
    "34": "U0RXD",        # RXD0 = IO3
}
GLOBAL = tuple(set(GPIO_NETS.values()))


def build():
    s = schgen.Sheet(PROJECT, "mcu.kicad_sch", "MCU", schgen.root_uuid(ROOT), SHEET_UUID, ref_base=200)

    s.text("ESP32-WROOM-32E. Pin map: docs/HARDWARE.md. Wi-Fi/BT unused, but keep the antenna\n"
           "area clear of copper (Espressif layout guide). Strapping pins 2, 12, 15 left open:\n"
           "12 must be low at boot (internal pull-down) or the flash runs at 1.8 V.", 40, 8)
    nets = {"2": "+3V3", "[1,15,38,39]": "GND"}
    nets.update(GPIO_NETS)
    for nc in ("17", "18", "19", "20", "21", "22", "32", "24", "14", "23"):  # flash pins, NC, IO2/12/15
        nets[nc] = None
    s.part("RF_Module:ESP32-WROOM-32E", "U", "ESP32-WROOM-32E", 60, 60, nets, None, GLOBAL)

    s.text("Decoupling at the module's 3V3 pin", 76, 16)
    s.part("Device:C_Small", "C", "10u", 78, 24, {"1": "+3V3", "2": "GND"}, {"Footprint": C0805}, GLOBAL)
    s.part("Device:C_Small", "C", "100n", 82, 24, {"1": "+3V3", "2": "GND"}, {"Footprint": C}, GLOBAL)

    s.text("EN: RC reset (10k / 1u, as on the DevKitC),\nreset button, and auto-reset from the USB sheet",
           12, 30)
    s.part("Device:R_Small", "R", "10k", 16, 40, {"1": "+3V3", "2": "EN"}, {"Footprint": R}, GLOBAL)
    s.part("Device:C_Small", "C", "1u", 20, 40, {"1": "EN", "2": "GND"}, {"Footprint": C}, GLOBAL)
    s.part("Switch:SW_Push", "SW", "RESET", 30, 40, {"1": "EN", "2": "GND"}, {"Footprint": BUTTON}, GLOBAL)

    s.text("BOOT (IO0 low at reset = download mode). Not in the original spec: a fallback\n"
           "if auto-reset fails on an early board. IO0 has an internal pull-up.", 12, 50)
    s.part("Switch:SW_Push", "SW", "BOOT", 30, 58, {"1": "IO0", "2": "GND"}, {"Footprint": BUTTON}, GLOBAL)

    text = s.render({
        "title": "HD Platinum remote replacement: MCU",
        "date": "2026-11-12",
        "rev": "0.1",
        "comments": ["Draft, generated by hardware/tools/gen_mcu.py", "Spec: docs/HARDWARE.md"],
    })
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    added = schgen.add_sheet_to_root(ROOT, PROJECT, SHEET_UUID, "MCU", "mcu.kicad_sch", 3, 70, 10)
    print("wrote", OUT, "| root sheet block", "added" if added else "already present")


if __name__ == "__main__":
    build()

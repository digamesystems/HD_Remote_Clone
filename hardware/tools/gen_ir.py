"""Generates hardware/hd_remote/ir.kicad_sch (first draft) from docs/HARDWARE.md:
two IR LEDs on VBAT with BC817-40 current sinks, bulk capacitance, and the
optional IR receiver footprint. Run once; after editing the sheet in KiCad,
don't rerun.

    python -I hardware/tools/gen_ir.py
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import schgen  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
PROJ_DIR = os.path.join(HERE, "..", "hd_remote")
ROOT = os.path.join(PROJ_DIR, "hd_remote.kicad_sch")
OUT = os.path.join(PROJ_DIR, "ir.kicad_sch")
PROJECT = "hd_remote"
SHEET_UUID = "5d7a1c42-8e6b-4f3a-b2c9-1e4f6a8b9c30"

R0603 = "Resistor_SMD:R_0603_1608Metric"
R0805 = "Resistor_SMD:R_0805_2012Metric"
C0603 = "Capacitor_SMD:C_0603_1608Metric"
C1206 = "Capacitor_SMD:C_1206_3216Metric"
IR_LED = "LED_THT:LED_D5.0mm_Horizontal_O1.27mm_Z3.0mm"
GLOBAL = ("IR_TX", "IR_RX")


def build():
    s = schgen.Sheet(PROJECT, "ir.kicad_sch", "IR", schgen.root_uuid(ROOT), SHEET_UUID, ref_base=300)

    s.text("IR transmitter: two 940 nm LEDs from VBAT, each with a constant-current sink.\n"
           "Base node clamped at ~1.3 V by two 1N4148 in series, so I_LED = (1.3 - 0.65) / R_E,\n"
           "~150 mA with 4.3 ohm, roughly constant from VBAT 3.3 to 4.2 V.\n"
           "VERIFY on the breadboard first (scope across R_E at 3.3 and 4.2 V), and check the\n"
           "TSAL6200 peak rating for our duty cycle (39.7 kHz, ~50 % measured, in bursts).", 8, 6)

    # Base drive and clamp
    s.part("Device:R_Small", "R", "470", 12, 34, {"1": "IR_TX", "2": "IR_BASE"},
           {"Footprint": R0603}, GLOBAL)
    s.part("Device:R_Small", "R", "100k", 12, 50, {"1": "IR_BASE", "2": "GND"},
           {"Footprint": R0603,
            "Description": "Keeps the LEDs off while GPIO 4 floats (boot, deep sleep)"}, GLOBAL)
    s.text("100k pull-down: LEDs off\nwhile GPIO 4 floats", 4, 56)
    s.part("Diode:1N4148W", "D", "1N4148W", 20, 42, {"2": "IR_BASE", "1": "IR_CLAMP"}, None, GLOBAL)
    s.part("Diode:1N4148W", "D", "1N4148W", 30, 42, {"2": "IR_CLAMP", "1": "GND"}, None, GLOBAL)

    # Two LED channels
    for i, gx in enumerate((48, 72), 1):
        s.part("Device:LED", "D", "TSAL6200", gx, 28, {"2": "VBAT", "1": "IR_K%d" % i},
               {"Footprint": IR_LED,
                "Description": "940 nm IR LED, +-17 deg (or a wider-angle part in one position)"}, GLOBAL)
        s.part("Transistor_BJT:BC817", "Q", "BC817-40", gx, 40,
               {"1": "IR_BASE", "3": "IR_K%d" % i, "2": "IR_E%d" % i}, None, GLOBAL)
        s.part("Device:R_Small", "R", "4.3", gx + 6, 50, {"1": "IR_E%d" % i, "2": "GND"},
               {"Footprint": R0805, "Description": "Sets I_LED ~150 mA; ~0.1 W peak, so 0805"}, GLOBAL)

    s.text("Test points: scope across each R_E (TP to GND)\n"
           "for I_LED = V / 4.3 ohm; IR_BASE shows the clamp.", 50, 58)
    tp = {"Footprint": "TestPoint:TestPoint_Pad_D1.5mm"}
    s.part("Connector:TestPoint", "TP", "IR_E1", 58, 46, {"1": "IR_E1"}, tp, GLOBAL)
    s.part("Connector:TestPoint", "TP", "IR_E2", 82, 46, {"1": "IR_E2"}, tp, GLOBAL)
    s.part("Connector:TestPoint", "TP", "IR_BASE", 20, 30, {"1": "IR_BASE"}, tp, GLOBAL)

    s.text("Bulk at the LEDs: the pulse current comes from here, not through the LDO.\n"
           "100 uF ceramic loses capacity with DC bias; check the derating curve.", 88, 20)
    s.part("Device:C_Small", "C", "100u", 92, 32, {"1": "VBAT", "2": "GND"}, {"Footprint": C1206}, GLOBAL)
    s.part("Device:C_Small", "C", "100n", 96, 32, {"1": "VBAT", "2": "GND"}, {"Footprint": C0603}, GLOBAL)

    # Optional receiver (diagnostics), not fitted in normal builds
    s.text("Optional IR receiver (diagnostics, DNP): TSOP382xx / VS1838B pinout OUT, GND, VS.\n"
           "Supply filter 100 ohm + 100 nF as on the breadboard.", 8, 66)
    s.part("Interface_Optical:TSOP382xx", "U", "TSOP38238", 16, 80,
           {"1": "IR_RX", "2": "GND", "3": "IR_VS"}, None, GLOBAL, dnp=True)
    s.part("Device:R_Small", "R", "100", 36, 78, {"1": "+3V3", "2": "IR_VS"},
           {"Footprint": R0603}, GLOBAL, dnp=True)
    s.part("Device:C_Small", "C", "100n", 40, 78, {"1": "IR_VS", "2": "GND"},
           {"Footprint": C0603}, GLOBAL, dnp=True)
    s.flag("IR_VS", 48, 78)  # fed from +3V3 through the 100 ohm, which ERC can't see through

    text = s.render({
        "title": "HD Platinum remote replacement: IR",
        "date": "2026-11-12",
        "rev": "0.1",
        "comments": ["Draft, generated by hardware/tools/gen_ir.py", "Spec: docs/HARDWARE.md"],
    })
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    added = schgen.add_sheet_to_root(ROOT, PROJECT, SHEET_UUID, "IR", "ir.kicad_sch", 4, 10, 30)
    print("wrote", OUT, "| root sheet block", "added" if added else "already present")


if __name__ == "__main__":
    build()
